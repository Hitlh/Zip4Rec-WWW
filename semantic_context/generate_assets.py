def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        raise ValueError(f"No CSV records found in {path}")
    return rows


def read_requested_item_ids(path: Path) -> set[int]:
    result: set[int] = set()
    with path.open(encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            stripped = line.strip()
            if not stripped:
                continue
            try:
                result.add(int(stripped))
            except ValueError as exc:
                raise ValueError(f"Invalid item ID at {path}:{line_number}") from exc
    if not result:
        raise ValueError(f"No item IDs found in {path}")
    return result


def stratified_item_sample(rows: list[dict[str, str]], size: int, seed: int) -> list[dict[str, str]]:
    if size <= 0:
        raise ValueError("--sample-size must be positive")
    if size >= len(rows):
        return rows
    rng = random.Random(seed)
    by_status: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        by_status[row.get("description_status", "unknown")].append(row)
    selected: list[dict[str, str]] = []
    statuses = sorted(by_status)
    for status in statuses:
        bucket = by_status[status]
        rng.shuffle(bucket)
        quota = max(1, round(size * len(bucket) / len(rows)))
        selected.extend(bucket[:quota])
    if len(selected) > size:
        rng.shuffle(selected)
        selected = selected[:size]
    elif len(selected) < size:
        selected_ids = {int(row["item_id"]) for row in selected}
        remainder = [row for row in rows if int(row["item_id"]) not in selected_ids]
        rng.shuffle(remainder)
        selected.extend(remainder[: size - len(selected)])
    return sorted(selected, key=lambda row: int(row["item_id"]))


def prepare_items(args: argparse.Namespace) -> int:
    if args.description_max_chars <= 0:
        raise ValueError("--description-max-chars must be positive")
    rows = read_csv(args.item_metadata)
    required = {
        "item_id", "original_item_id", "title", "categories", "brand",
        "description_clean", "description_status",
    }
    missing = required.difference(rows[0])
    if missing:
        raise ValueError(
            f"Item metadata lacks {sorted(missing)}. "
            "Use filtered/item_metadata.csv generated by semantic_context.pipeline prepare."
        )
    if args.item_ids:
        requested = read_requested_item_ids(args.item_ids)
        rows = [row for row in rows if int(row["item_id"]) in requested]
        found = {int(row["item_id"]) for row in rows}
        if found != requested:
            raise ValueError(f"Missing requested item IDs: {sorted(requested - found)[:20]}")
    if args.sample_size is not None:
        rows = stratified_item_sample(rows, args.sample_size, args.seed)
    if not rows:
        raise ValueError("Item selection is empty")

    reuse_paths = list(getattr(args, "reuse_item_summaries", []) or [])
    reusable_by_item: dict[int, dict[str, Any]] = {}
    for path in reuse_paths:
        for cached in read_jsonl(path):
            item_id = int(cached["item_id"])
            previous = reusable_by_item.get(item_id)
            if previous is not None and previous.get("summary_hash") != cached.get("summary_hash"):
                raise ValueError(f"Conflicting reusable summaries for item {item_id}")
            reusable_by_item[item_id] = cached

    prepare_empty_directory(args.output_dir)
    sources: list[dict[str, Any]] = []
    requests: list[dict[str, Any]] = []
    truncated_descriptions = 0
    reused_items = 0
    for row in sorted(rows, key=lambda value: int(value["item_id"])):
        full_description = row["description_clean"].strip()
        description = full_description
        if len(description) > args.description_max_chars:
            description = description[: args.description_max_chars].rsplit(" ", 1)[0].strip()
            if not description:
                description = full_description[: args.description_max_chars]
            truncated_descriptions += 1
        source_payload = {
            "title": row["title"].strip(),
            "categories": row["categories"].strip(),
            "brand": row["brand"].strip(),
            "description_clean": description,
        }
        source_hash = sha256_json(source_payload)
        cache_key = sha256_json(
            {
                "prompt_version": ITEM_PROMPT_VERSION,
                "model": args.model,
                "temperature": 0,
                "response_format": args.response_format,
                "source_hash": source_hash,
            }
        )
        custom_id = f"item-{int(row['item_id']):05d}-{cache_key[:16]}"
        cached = reusable_by_item.get(int(row["item_id"]))
        if cached is not None:
            if cached.get("custom_id") != custom_id or cached.get("cache_key") != cache_key:
                raise ValueError(
                    f"Reusable summary cache key does not match current request for item {row['item_id']}"
                )
            validate_item_summary(cached["summary"])
            reused_items += 1
            continue
        source = {
            "custom_id": custom_id,
            "cache_key": cache_key,
            "prompt_version": ITEM_PROMPT_VERSION,
            "requested_model": args.model,
            "response_format": args.response_format,
            "item_id": int(row["item_id"]),
            "original_item_id": row["original_item_id"],
            "source_hash": source_hash,
            "description_full_sha256": sha256_bytes(full_description.encode("utf-8")),
            "description_full_char_length": len(full_description),
            "description_sent_char_length": len(description),
            "description_was_capped": len(description) < len(full_description),
            "description_status": row["description_status"].strip(),
            **source_payload,
        }
        sources.append(source)
        requests.append(
            make_request(
                custom_id=custom_id,
                model=args.model,
                system_prompt=item_system_prompt(),
                user_prompt=item_user_prompt(source_payload),
                schema_name="amazonmusic_item_profile",
                schema=ITEM_SCHEMA,
                response_format_mode=args.response_format,
                max_tokens=420,
            )
        )
    write_jsonl_exclusive(args.output_dir / "item_sources.jsonl", sources)
    write_jsonl_exclusive(args.output_dir / "requests.jsonl", requests)
    write_json_exclusive(args.output_dir / "schema.json", ITEM_SCHEMA)
    write_json_exclusive(
        args.output_dir / "manifest.json",
        {
            "asset_type": "item_summary_requests",
            "prompt_version": ITEM_PROMPT_VERSION,
            "requested_model": args.model,
            "response_format": args.response_format,
            "temperature": 0,
            "records": len(sources),
            "selected_items": len(rows),
            "reused_items": reused_items,
            "reuse_item_summaries": [str(path.resolve()) for path in reuse_paths],
            "reuse_item_summaries_sha256": {
                str(path.resolve()): sha256_file(path) for path in reuse_paths
            },
            "seed": args.seed,
            "description_max_chars": args.description_max_chars,
            "descriptions_capped": truncated_descriptions,
            "source_item_metadata": str(args.item_metadata.resolve()),
            "source_item_metadata_sha256": sha256_file(args.item_metadata),
            "item_ids_filter": str(args.item_ids.resolve()) if args.item_ids else None,
            "item_ids_filter_sha256": sha256_file(args.item_ids) if args.item_ids else None,
            "requests_sha256": sha256_file(args.output_dir / "requests.jsonl"),
        },
    )
    print(
        json.dumps(
            {
                "selected_items": len(rows),
                "records": len(sources),
                "reused_items": reused_items,
                "output_dir": str(args.output_dir),
            },
            indent=2,
        )
    )
    return 0


def result_map(path: Path) -> tuple[dict[str, dict[str, Any]], list[str]]:
    mapped: dict[str, dict[str, Any]] = {}
    duplicates: list[str] = []
    for row in read_jsonl(path):
        custom_id = row.get("custom_id")
        if not isinstance(custom_id, str) or not custom_id:
            raise ValueError("Every result row must contain custom_id")
        if custom_id in mapped:
            duplicates.append(custom_id)
        mapped[custom_id] = row
    return mapped, duplicates


def parse_items(args: argparse.Namespace) -> int:
    sources = read_jsonl(args.request_dir / "item_sources.jsonl")
    results, duplicates = result_map(args.results)
    prepare_empty_directory(args.output_dir)
    valid: list[dict[str, Any]] = []
    failures: list[dict[str, Any]] = []
    raw_rows: list[dict[str, Any]] = []
    missing_results = 0
    expected_ids = {row["custom_id"] for row in sources}
    for source in sources:
        custom_id = source["custom_id"]
        result = results.get(custom_id)
        if result is None:
            missing_results += 1
            if not getattr(args, "allow_partial_results", False):
                failures.append({"custom_id": custom_id, "item_id": source["item_id"], "error": "missing_result"})
            continue
        raw_rows.append(result)
        try:
            if result.get("error"):
                raise ValueError(f"Provider error: {canonical_json(result['error'])}")
            body = response_body_from_result(result)
            content = content_from_chat_completion_body(body)
            summary = validate_item_summary(parse_json_content(content))
            valid.append(
                {
                    **source,
                    "response_id": body.get("id"),
                    "response_model": body.get("model"),
                    "system_fingerprint": body.get("system_fingerprint"),
                    "usage": body.get("usage", {}),
                    "provider_metadata": result.get("provider_metadata", {}),
                    "raw_content": content,
                    "summary": summary,
                    "summary_hash": sha256_json(summary),
                }
            )
        except (ValueError, TypeError, KeyError) as exc:
            failures.append(
                {"custom_id": custom_id, "item_id": source["item_id"], "error": str(exc)}
            )
    write_jsonl_exclusive(args.output_dir / "item_summaries.jsonl", valid)
    write_jsonl_exclusive(args.output_dir / "failures.jsonl", failures)
    write_jsonl_exclusive(args.output_dir / "raw_result_rows.jsonl", raw_rows)
    report = {
        "asset_type": "validated_item_summaries",
        "requested": len(sources),
        "returned_expected": len(sources) - missing_results,
        "missing_results": missing_results,
        "allow_partial_results": bool(getattr(args, "allow_partial_results", False)),
        "valid": len(valid),
        "failed": len(failures),
        "valid_fraction_of_returned": (
            len(valid) / (len(sources) - missing_results)
            if len(sources) != missing_results else 0.0
        ),
        "duplicate_result_custom_ids": sorted(set(duplicates)),
        "unexpected_result_custom_ids": sorted(set(results) - expected_ids),
        "request_manifest_sha256": sha256_file(args.request_dir / "manifest.json"),
        "results_path": str(args.results.resolve()),
        "results_sha256": sha256_file(args.results),
        "response_models": dict(sorted(Counter(row.get("response_model") or "unknown" for row in valid).items())),
    }
    write_json_exclusive(args.output_dir / "validation_report.json", report)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0 if not failures and not duplicates and not (set(results) - expected_ids) else 2


def static_empty_profile() -> dict[str, Any]:
    return {
        "preference_summary": "Insufficient earlier positive-history evidence to infer stable long-term preferences.",
        "preferred_genres": [],
        "preferred_artists_or_scenes": [],
        "preferred_eras": [],
        "preferred_moods_or_styles": [],
        "diversity": "unknown",
        "evidence_strength": "sparse",
        "uncertainties": ["No long-term history items were available before the recent-history window."],
    }


def prepare_profiles(args: argparse.Namespace) -> int:
    contexts = read_jsonl(args.contexts, allow_empty=True)
    item_rows = read_jsonl(args.item_summaries)
    summaries = {int(row["item_id"]): row for row in item_rows}
    prepare_empty_directory(args.output_dir)
    request_sources: list[dict[str, Any]] = []
    requests: list[dict[str, Any]] = []
    static_profiles: list[dict[str, Any]] = []
    for context in contexts:
        long_ids = list(map(int, context["long_history_item_ids"]))
        missing = [item_id for item_id in long_ids if item_id not in summaries]
        if missing:
            raise ValueError(
                f"Context {context['profile_history_key']} lacks item summaries: {missing[:20]}"
            )
        ordered_summary_hashes = [summaries[item_id]["summary_hash"] for item_id in long_ids]
        cache_key = sha256_json(
            {
                "prompt_version": PROFILE_PROMPT_VERSION,
                "model": args.model,
                "temperature": 0,
                "response_format": args.response_format,
                "ordered_long_history_item_ids": long_ids,
                "ordered_item_summary_hashes": ordered_summary_hashes,
            }
        )
        common = {
            "profile_history_key": context["profile_history_key"],
            "profile_cache_key": cache_key,
            "prompt_version": PROFILE_PROMPT_VERSION,
            "requested_model": args.model,
            "response_format": args.response_format,
            "long_history_item_ids": long_ids,
            "ordered_item_summary_hashes": ordered_summary_hashes,
            "long_history_count": len(long_ids),
        }
        if not long_ids:
            profile = static_empty_profile()
            static_profiles.append({**common, "generation_mode": "deterministic_empty", "profile": profile, "profile_hash": sha256_json(profile)})
            continue
        custom_id = f"profile-{cache_key[:24]}"
        input_items = [
            {
                "item_id": item_id,
                "title": summaries[item_id]["title"],
                "compact_summary": summaries[item_id]["summary"]["compact_summary"],
                "uncertainties": summaries[item_id]["summary"]["uncertainties"],
            }
            for item_id in long_ids
        ]
        request_sources.append({**common, "custom_id": custom_id, "input_items": input_items})
        requests.append(
            make_request(
                custom_id=custom_id,
                model=args.model,
                system_prompt=profile_system_prompt(),
                user_prompt=profile_user_prompt(input_items),
                schema_name="amazonmusic_user_profile",
                schema=PROFILE_SCHEMA,
                response_format_mode=args.response_format,
                max_tokens=620,
            )
        )
    write_jsonl_exclusive(args.output_dir / "profile_request_sources.jsonl", request_sources)
    write_jsonl_exclusive(args.output_dir / "requests.jsonl", requests)
    write_jsonl_exclusive(args.output_dir / "static_profiles.jsonl", static_profiles)
    write_json_exclusive(args.output_dir / "schema.json", PROFILE_SCHEMA)
    write_json_exclusive(
        args.output_dir / "manifest.json",
        {
            "asset_type": "user_profile_requests",
            "prompt_version": PROFILE_PROMPT_VERSION,
            "requested_model": args.model,
            "response_format": args.response_format,
            "temperature": 0,
            "contexts": len(contexts),
            "api_requests": len(requests),
            "deterministic_empty_profiles": len(static_profiles),
            "contexts_path": str(args.contexts.resolve()),
            "contexts_sha256": sha256_file(args.contexts),
            "item_summaries_path": str(args.item_summaries.resolve()),
            "item_summaries_sha256": sha256_file(args.item_summaries),
            "requests_sha256": sha256_file(args.output_dir / "requests.jsonl"),
        },
    )
    print(json.dumps({"contexts": len(contexts), "api_requests": len(requests), "static": len(static_profiles)}, indent=2))
    return 0


def parse_profiles(args: argparse.Namespace) -> int:
    sources = read_jsonl(args.request_dir / "profile_request_sources.jsonl", allow_empty=True)
    static_profiles = read_jsonl(args.request_dir / "static_profiles.jsonl", allow_empty=True)
    results, duplicates = result_map(args.results) if sources else ({}, [])
    prepare_empty_directory(args.output_dir)
    valid = list(static_profiles)
    failures: list[dict[str, Any]] = []
    raw_rows: list[dict[str, Any]] = []
    missing_results = 0
    expected_ids = {row["custom_id"] for row in sources}
    for source in sources:
        custom_id = source["custom_id"]
        result = results.get(custom_id)
        if result is None:
            missing_results += 1
            if not getattr(args, "allow_partial_results", False):
                failures.append({"custom_id": custom_id, "profile_cache_key": source["profile_cache_key"], "error": "missing_result"})
            continue
        raw_rows.append(result)
        try:
            if result.get("error"):
                raise ValueError(f"Provider error: {canonical_json(result['error'])}")
            body = response_body_from_result(result)
            content = content_from_chat_completion_body(body)
            profile = validate_user_profile(
                parse_json_content(content), long_history_count=int(source["long_history_count"])
            )
            valid.append(
                {
                    **{key: value for key, value in source.items() if key != "input_items"},
                    "generation_mode": "gpt",
                    "response_id": body.get("id"),
                    "response_model": body.get("model"),
                    "system_fingerprint": body.get("system_fingerprint"),
                    "usage": body.get("usage", {}),
                    "provider_metadata": result.get("provider_metadata", {}),
                    "raw_content": content,
                    "profile": profile,
                    "profile_hash": sha256_json(profile),
                }
            )
        except (ValueError, TypeError, KeyError) as exc:
            failures.append(
                {"custom_id": custom_id, "profile_cache_key": source["profile_cache_key"], "error": str(exc)}
            )
    write_jsonl_exclusive(args.output_dir / "user_profiles.jsonl", valid)
    write_jsonl_exclusive(args.output_dir / "failures.jsonl", failures)
    write_jsonl_exclusive(args.output_dir / "raw_result_rows.jsonl", raw_rows)
    report = {
        "asset_type": "validated_user_profiles",
        "requested": len(sources),
        "returned_expected": len(sources) - missing_results,
        "missing_results": missing_results,
        "allow_partial_results": bool(getattr(args, "allow_partial_results", False)),
        "static": len(static_profiles),
        "valid_total": len(valid),
        "failed": len(failures),
        "duplicate_result_custom_ids": sorted(set(duplicates)),
        "unexpected_result_custom_ids": sorted(set(results) - expected_ids),
        "request_manifest_sha256": sha256_file(args.request_dir / "manifest.json"),
        "results_path": str(args.results.resolve()),
        "results_sha256": sha256_file(args.results),
        "response_models": dict(sorted(Counter(row.get("response_model") or "unknown" for row in valid if row.get("generation_mode") == "gpt").items())),
    }
    write_json_exclusive(args.output_dir / "validation_report.json", report)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0 if not failures and not duplicates and not (set(results) - expected_ids) else 2



def parse_args():
    p = argparse.ArgumentParser(description=__doc__)
    commands = p.add_subparsers(dest='command', required=True)
    items = commands.add_parser('prepare-items')
    items.add_argument('--item-metadata', type=Path, required=True)
    items.add_argument('--output-dir', type=Path, required=True)
    items.add_argument('--model', default='gpt-4o')
    items.add_argument('--response-format', choices=['json-schema', 'json-object'], default='json-schema')
    items.add_argument('--description-max-chars', type=int, default=4000)
    items.add_argument('--sample-size', type=int)
    items.add_argument('--item-ids', type=Path)
    items.add_argument('--seed', type=int, default=42)
    profiles = commands.add_parser('prepare-profiles')
    profiles.add_argument('--contexts', type=Path, required=True)
    profiles.add_argument('--item-summaries', type=Path, required=True)
    profiles.add_argument('--output-dir', type=Path, required=True)
    profiles.add_argument('--model', default='gpt-4o')
    profiles.add_argument('--response-format', choices=['json-schema', 'json-object'], default='json-schema')
    for name in ['parse-items', 'parse-profiles']:
        parse = commands.add_parser(name)
        parse.add_argument('--request-dir', type=Path, required=True)
        parse.add_argument('--results', type=Path, required=True)
        parse.add_argument('--output-dir', type=Path, required=True)
        parse.add_argument('--allow-partial-results', action='store_true')
    return p.parse_args()


def main():
    args = parse_args()
    functions = {'prepare-items': prepare_items, 'parse-items': parse_items,
                 'prepare-profiles': prepare_profiles, 'parse-profiles': parse_profiles}
    return functions[args.command](args)


if __name__ == '__main__':
    raise SystemExit(main())
